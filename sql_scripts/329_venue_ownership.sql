-- Story #329: venue ownership
-- Links users to the venues they manage. A venue may have several owners, or none (for example a staff-seeded listing).
-- Idempotent: safe to re-run.
--
-- Existing venues have no recorded owner, so after this script only staff (Users.Moderator = true) can edit them.
-- To give an existing venue to its owner, insert a link, for example:
--   INSERT INTO public."Linker_UserToVenue" ("UserID", "VenueID", "Role") VALUES (<userId>, <venueId>, 'Owner')
--   ON CONFLICT ("UserID", "VenueID") DO NOTHING;

BEGIN;

CREATE TABLE IF NOT EXISTS public."Linker_UserToVenue" (
    "Linker_UserToVenueID" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "UserID" integer NOT NULL,
    "VenueID" integer NOT NULL,
    "Role" varchar(255) NOT NULL DEFAULT 'Owner'
);

-- A user is linked to a given venue at most once.
CREATE UNIQUE INDEX IF NOT EXISTS "IX_Linker_UserToVenue_UserID_VenueID"
    ON public."Linker_UserToVenue" ("UserID", "VenueID");

CREATE INDEX IF NOT EXISTS "IX_Linker_UserToVenue_VenueID"
    ON public."Linker_UserToVenue" ("VenueID");

-- Links are removed together with their venue.
DO $migration$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'FK_Linker_UserToVenue_Venues_VenueID' AND conrelid = 'public."Linker_UserToVenue"'::regclass
    ) THEN
        ALTER TABLE public."Linker_UserToVenue"
            ADD CONSTRAINT "FK_Linker_UserToVenue_Venues_VenueID"
            FOREIGN KEY ("VenueID") REFERENCES public."Venues" ("VenueID") ON DELETE CASCADE;
    END IF;
END
$migration$;

COMMIT;
