-- Picture metadata extensions.
ALTER TABLE "Pictures"
	ADD COLUMN IF NOT EXISTS "NormalizedURL" text,
	ADD COLUMN IF NOT EXISTS "Byline" varchar(2000),
	ADD COLUMN IF NOT EXISTS "Updated" timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP;

CREATE INDEX IF NOT EXISTS "IX_Pictures_NormalizedURL"
	ON "Pictures" ("NormalizedURL");

-- Peer media entity: Videos.
CREATE TABLE IF NOT EXISTS "Videos" (
	"VideoID" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	"UserID" integer,
	"ArtistID" integer,
	"Title" varchar(1000),
	"Byline" varchar(2000),
	"Description" text,
	"EmbedURL" text NOT NULL,
	"URL" text,
	"ThumbnailURL" text,
	"Provider" varchar(40) NOT NULL DEFAULT 'vimeo',
	"ProviderVideoID" varchar(200),
	"NormalizedEmbedURL" text,
	"Created" timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
	"Updated" timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
	CONSTRAINT "FK_Videos_Users_UserID"
		FOREIGN KEY ("UserID") REFERENCES "Users" ("UserID") ON DELETE SET NULL,
	CONSTRAINT "FK_Videos_Artists_ArtistID"
		FOREIGN KEY ("ArtistID") REFERENCES "Artists" ("ArtistID") ON DELETE SET NULL,
	CONSTRAINT "CK_Video_Provider"
		CHECK ("Provider" IN ('vimeo', 'youtube'))
);

CREATE INDEX IF NOT EXISTS "IX_Videos_NormalizedEmbedURL"
	ON "Videos" ("NormalizedEmbedURL");

-- Scoped galleries (entity scope + owner).
CREATE TABLE IF NOT EXISTS "Galleries" (
	"GalleryID" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	"ScopeType" varchar(100) NOT NULL,
	"ScopeEntityID" integer NOT NULL,
	"OwnerUserID" integer,
	"OwnerArtistID" integer,
	"Title" varchar(250),
	"Description" text,
	"IsPrimary" boolean NOT NULL DEFAULT FALSE,
	"Created" timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
	"Updated" timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
	CONSTRAINT "FK_Galleries_Users_OwnerUserID"
		FOREIGN KEY ("OwnerUserID") REFERENCES "Users" ("UserID") ON DELETE SET NULL,
	CONSTRAINT "FK_Galleries_Artists_OwnerArtistID"
		FOREIGN KEY ("OwnerArtistID") REFERENCES "Artists" ("ArtistID") ON DELETE SET NULL,
	CONSTRAINT "CK_Gallery_SingleOwner"
		CHECK ((CASE WHEN "OwnerUserID" IS NOT NULL THEN 1 ELSE 0 END + CASE WHEN "OwnerArtistID" IS NOT NULL THEN 1 ELSE 0 END) <= 1)
);

CREATE INDEX IF NOT EXISTS "IX_Galleries_ScopeType_ScopeEntityID"
	ON "Galleries" ("ScopeType", "ScopeEntityID");

