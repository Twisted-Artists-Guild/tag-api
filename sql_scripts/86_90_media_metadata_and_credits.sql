-- Credit parties: account-linked or external collaborators.
CREATE TABLE IF NOT EXISTS "CreditParties" (
	"CreditPartyID" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	"UserID" integer,
	"ArtistID" integer,
	"DisplayName" varchar(250),
	"ExternalURL" text,
	"BioNote" varchar(2000),
	"Created" timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
	CONSTRAINT "FK_CreditParties_Users_UserID"
		FOREIGN KEY ("UserID") REFERENCES "Users" ("UserID") ON DELETE SET NULL,
	CONSTRAINT "FK_CreditParties_Artists_ArtistID"
		FOREIGN KEY ("ArtistID") REFERENCES "Artists" ("ArtistID") ON DELETE SET NULL,
	CONSTRAINT "CK_CreditParty_HasIdentity"
		CHECK (
			(CASE WHEN "UserID" IS NOT NULL THEN 1 ELSE 0 END +
			 CASE WHEN "ArtistID" IS NOT NULL THEN 1 ELSE 0 END +
			 CASE WHEN "DisplayName" IS NOT NULL AND LENGTH(TRIM("DisplayName")) > 0 THEN 1 ELSE 0 END) >= 1
		)
);

-- Media-to-credit assignments (pictures, videos, and blogs).
CREATE TABLE IF NOT EXISTS "MediaCredits" (
	"MediaCreditID" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	"PictureID" integer,
	"VideoID" integer,
	"BlogID" integer,
	"CreditPartyID" integer NOT NULL,
	"CreditRoleID" integer NOT NULL,
	"CreditText" varchar(2000),
	"SortOrder" integer NOT NULL DEFAULT 0,
	CONSTRAINT "FK_MediaCredits_Pictures_PictureID"
		FOREIGN KEY ("PictureID") REFERENCES "Pictures" ("PictureID") ON DELETE CASCADE,
	CONSTRAINT "FK_MediaCredits_Videos_VideoID"
		FOREIGN KEY ("VideoID") REFERENCES "Videos" ("VideoID") ON DELETE CASCADE,
	CONSTRAINT "FK_MediaCredits_Blogs_BlogID"
		FOREIGN KEY ("BlogID") REFERENCES "Blogs" ("BlogID") ON DELETE CASCADE,
	CONSTRAINT "FK_MediaCredits_CreditParties_CreditPartyID"
		FOREIGN KEY ("CreditPartyID") REFERENCES "CreditParties" ("CreditPartyID") ON DELETE CASCADE,
	CONSTRAINT "FK_MediaCredits_CreditRoles_CreditRoleID"
		FOREIGN KEY ("CreditRoleID") REFERENCES "CreditRoles" ("CreditRoleID") ON DELETE RESTRICT,
	CONSTRAINT "CK_MediaCredit_ExactlyOneMedia"
		CHECK ((CASE WHEN "PictureID" IS NOT NULL THEN 1 ELSE 0 END + CASE WHEN "VideoID" IS NOT NULL THEN 1 ELSE 0 END + CASE WHEN "BlogID" IS NOT NULL THEN 1 ELSE 0 END) = 1)
);

-- Idempotent upgrade path for existing databases that may have pre-blog MediaCredits.
ALTER TABLE "MediaCredits"
	ADD COLUMN IF NOT EXISTS "BlogID" integer;

DO $$
BEGIN
	IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'FK_MediaCredits_Blogs_BlogID') THEN
		ALTER TABLE "MediaCredits" ADD CONSTRAINT "FK_MediaCredits_Blogs_BlogID"
			FOREIGN KEY ("BlogID") REFERENCES "Blogs" ("BlogID") ON DELETE CASCADE;
	END IF;

	IF EXISTS (
		SELECT 1
		FROM pg_constraint
		WHERE conname = 'CK_MediaCredit_ExactlyOneMedia'
		  AND conrelid = '"MediaCredits"'::regclass
	) THEN
		ALTER TABLE "MediaCredits" DROP CONSTRAINT "CK_MediaCredit_ExactlyOneMedia";
	END IF;

	IF NOT EXISTS (
		SELECT 1
		FROM pg_constraint
		WHERE conname = 'CK_MediaCredit_ExactlyOneMedia'
		  AND conrelid = '"MediaCredits"'::regclass
	) THEN
		ALTER TABLE "MediaCredits" ADD CONSTRAINT "CK_MediaCredit_ExactlyOneMedia"
			CHECK ((CASE WHEN "PictureID" IS NOT NULL THEN 1 ELSE 0 END + CASE WHEN "VideoID" IS NOT NULL THEN 1 ELSE 0 END + CASE WHEN "BlogID" IS NOT NULL THEN 1 ELSE 0 END) = 1);
	END IF;
END $$;

