-- Story #421 (tag-web): event hosts and role-based permissions
-- Adds "EventHosts": people, artists and venues that take part in an event besides its owner, with their role on it
-- (1 ReadOnly, 2 CheckIn, 3 Staff, 4 Admin). The owner is not stored: it is the event's artist, or its venue for a
-- venue-hosted event, so every event has exactly one owner. Existing events need no rows and keep working.
-- Idempotent: safe to re-run. No existing data is changed.
--
-- Run against the right database first and check which server you are on:
--   SELECT current_database(), inet_server_addr();

BEGIN;

CREATE TABLE IF NOT EXISTS public."EventHosts" (
    "EventHostID" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "EventID" integer NOT NULL REFERENCES public."Events" ("EventID") ON DELETE CASCADE,
    "HostType" character varying(16) NOT NULL,
    "HostID" integer NOT NULL,
    "Role" integer NOT NULL,
    "CreatedAt" timestamp with time zone NOT NULL DEFAULT now(),
    "CreatedByUserID" integer NULL,
    CONSTRAINT "CK_EventHosts_HostType" CHECK ("HostType" IN ('User', 'Artist', 'Venue')),
    CONSTRAINT "CK_EventHosts_Role" CHECK ("Role" BETWEEN 1 AND 4)
);

CREATE UNIQUE INDEX IF NOT EXISTS "IX_EventHosts_EventID_HostType_HostID"
    ON public."EventHosts" ("EventID", "HostType", "HostID");

CREATE INDEX IF NOT EXISTS "IX_EventHosts_HostType_HostID"
    ON public."EventHosts" ("HostType", "HostID");

COMMIT;
