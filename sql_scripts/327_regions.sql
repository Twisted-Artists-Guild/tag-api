-- Story #327: shared regions for venues and artists
-- A staff-managed list of regional community groupings, and the links from venues and artists to their regions.
-- A region is statewide, multistate, or an area within one state (such as a metro area).
-- Idempotent: safe to re-run. Re-running never overwrites a region that staff renamed, edited or deactivated.
--
-- The old free-text "Addresses"."Region" column is not touched. It stays until the artist migration story is complete.
--
-- Run against the right database first and check which server you are on:
--   SELECT current_database(), inet_server_addr();

BEGIN;

CREATE TABLE IF NOT EXISTS public."Regions" (
    "RegionID" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Name" varchar(100) NOT NULL,
    "Slug" varchar(100) NOT NULL,
    "Type" varchar(20) NOT NULL,
    "States" text[] NOT NULL DEFAULT '{}',
    "IsActive" boolean NOT NULL DEFAULT true
);

-- The slug is the stable key used by filters, and two regions can't share a name in any letter case.
CREATE UNIQUE INDEX IF NOT EXISTS "IX_Regions_Slug"
    ON public."Regions" ("Slug");

CREATE UNIQUE INDEX IF NOT EXISTS "IX_Regions_Name_Lower"
    ON public."Regions" (lower("Name"));

CREATE TABLE IF NOT EXISTS public."Linker_VenueToRegion" (
    "Linker_VenueToRegionID" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "VenueID" integer NOT NULL,
    "RegionID" integer NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS "IX_Linker_VenueToRegion_VenueID_RegionID"
    ON public."Linker_VenueToRegion" ("VenueID", "RegionID");

-- Used when filtering venues by region.
CREATE INDEX IF NOT EXISTS "IX_Linker_VenueToRegion_RegionID"
    ON public."Linker_VenueToRegion" ("RegionID");

CREATE TABLE IF NOT EXISTS public."Linker_ArtistToRegion" (
    "Linker_ArtistToRegionID" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ArtistID" integer NOT NULL,
    "RegionID" integer NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS "IX_Linker_ArtistToRegion_ArtistID_RegionID"
    ON public."Linker_ArtistToRegion" ("ArtistID", "RegionID");

CREATE INDEX IF NOT EXISTS "IX_Linker_ArtistToRegion_RegionID"
    ON public."Linker_ArtistToRegion" ("RegionID");

DO $migration$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'CK_Regions_Type' AND conrelid = 'public."Regions"'::regclass
    ) THEN
        ALTER TABLE public."Regions"
            ADD CONSTRAINT "CK_Regions_Type" CHECK ("Type" IN ('Statewide', 'Multistate', 'WithinState'));
    END IF;

    -- Links are removed together with their venue.
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'FK_Linker_VenueToRegion_Venues_VenueID' AND conrelid = 'public."Linker_VenueToRegion"'::regclass
    ) THEN
        ALTER TABLE public."Linker_VenueToRegion"
            ADD CONSTRAINT "FK_Linker_VenueToRegion_Venues_VenueID"
            FOREIGN KEY ("VenueID") REFERENCES public."Venues" ("VenueID") ON DELETE CASCADE;
    END IF;

    -- Regions are deactivated, never deleted, so a region that is still in use can't be removed.
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'FK_Linker_VenueToRegion_Regions_RegionID' AND conrelid = 'public."Linker_VenueToRegion"'::regclass
    ) THEN
        ALTER TABLE public."Linker_VenueToRegion"
            ADD CONSTRAINT "FK_Linker_VenueToRegion_Regions_RegionID"
            FOREIGN KEY ("RegionID") REFERENCES public."Regions" ("RegionID") ON DELETE RESTRICT;
    END IF;

    -- Links are removed together with their artist.
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'FK_Linker_ArtistToRegion_Artists_ArtistID' AND conrelid = 'public."Linker_ArtistToRegion"'::regclass
    ) THEN
        ALTER TABLE public."Linker_ArtistToRegion"
            ADD CONSTRAINT "FK_Linker_ArtistToRegion_Artists_ArtistID"
            FOREIGN KEY ("ArtistID") REFERENCES public."Artists" ("ArtistID") ON DELETE CASCADE;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'FK_Linker_ArtistToRegion_Regions_RegionID' AND conrelid = 'public."Linker_ArtistToRegion"'::regclass
    ) THEN
        ALTER TABLE public."Linker_ArtistToRegion"
            ADD CONSTRAINT "FK_Linker_ArtistToRegion_Regions_RegionID"
            FOREIGN KEY ("RegionID") REFERENCES public."Regions" ("RegionID") ON DELETE RESTRICT;
    END IF;
END
$migration$;

